"""SQL 文件写出：表结构、数据、视图；排除表仅结构。"""
from __future__ import annotations

import time
from pathlib import Path
from typing import TYPE_CHECKING, Callable

from app import APP_NAME, __version__

from .literal import quote_ident
from .models import (DatabaseResult, ExportOptions, KIND_TABLE, KIND_VIEW,
                     TableResult)

if TYPE_CHECKING:
    from ..dialects.base import Dialect

ProgressCallback = Callable[[str, int, int], None]


class SqlWriter:
    """把分类结果写成一个可导入的 .sql 文件。"""

    def __init__(self, dialect: "Dialect", options: ExportOptions, cancel_event=None,
                 log: Callable[[str], None] | None = None) -> None:
        self.dialect = dialect
        self.options = options
        self.cancel_event = cancel_event
        self.log = log or (lambda message: None)

    def write_database(self, db: str, classified, path: Path,
                       progress_cb: ProgressCallback | None = None) -> DatabaseResult:
        result = DatabaseResult(db=db, path=str(path))
        tables = [item for item in classified
                  if not item.info.is_view and item.export_structure]
        views = [item for item in classified
                 if item.info.is_view and item.export_structure]
        total = len(tables) + len(views)
        done = 0
        excluded = [item.info.name for item in classified
                    if not item.info.is_view and not item.export_data]
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("w", encoding="utf-8", newline="\n") as handle:
            self._write_header(handle, db, excluded)
            for item in tables + views:
                if self._cancelled():
                    result.cancelled = True
                    break
                if item.info.is_view:
                    self._write_view(handle, db, item, result)
                    done += 1
                    if progress_cb:
                        progress_cb(item.info.name, 0, done)
                    continue
                rows = self._write_table(handle, db, item, result, progress_cb, done, total)
                done += 1
                if progress_cb:
                    progress_cb(item.info.name, rows, done)
                if result.cancelled:
                    break
            handle.write("\nSET FOREIGN_KEY_CHECKS=1;\n")
        return result

    def _write_header(self, handle, db: str, excluded: list[str]) -> None:
        handle.write("-- database %s data export\n" % db)
        handle.write("-- generated by %s v%s at %s\n"
                     % (APP_NAME, __version__, time.strftime("%Y-%m-%d %H:%M:%S")))
        if excluded:
            handle.write("-- excluded tables (structure only): %s\n" % ", ".join(excluded))
        handle.write("SET NAMES utf8mb4;\nSET FOREIGN_KEY_CHECKS=0;\n\n")

    def _write_table(self, handle, db: str, item, result: DatabaseResult,
                     progress_cb: ProgressCallback | None, done: int, total: int) -> int:
        table = item.info.name
        suffix = "export: data" if item.export_data else "excluded: structure only"
        handle.write("\n-- ----------------------------\n-- table %s (%s)\n"
                     "-- ----------------------------\n" % (quote_ident(table), suffix))
        try:
            if self.options.drop_before_create:
                handle.write(self.dialect.drop_table_sql(table) + "\n")
            ddl = self.dialect.create_table_sql(db, table).rstrip().rstrip(";")
            handle.write(ddl + ";\n\n")
        except Exception as exc:
            self._record_error(result, "表 %s 结构导出失败：%s" % (table, exc))
            result.tables.append(TableResult(table, KIND_TABLE, 0, str(exc)))
            return 0
        rows_written = 0
        if item.export_data:
            try:
                for columns, rows in self.dialect.stream_rows(db, table, self.options.batch_size):
                    if not rows:
                        continue
                    column_sql = ",".join(quote_ident(column) for column in columns)
                    prefix = "INSERT INTO %s (%s) VALUES " % (quote_ident(table), column_sql)
                    for row in rows:
                        values = ",".join(self.dialect.literal(value, self.options)
                                          for value in row)
                        handle.write(prefix + "(" + values + ");\n")
                        rows_written += 1
                    if self._cancelled():
                        result.cancelled = True
                        break
                    if progress_cb:
                        progress_cb(table, rows_written, done)
            except Exception as exc:
                self._record_error(result, "表 %s 数据导出失败：%s" % (table, exc))
        handle.write("-- table %s rows: %d\n" % (quote_ident(table), rows_written))
        result.tables.append(TableResult(table, KIND_TABLE, rows_written))
        self.log("    [导出] %s %d 行" % (table, rows_written))
        return rows_written

    def _write_view(self, handle, db: str, item, result: DatabaseResult) -> None:
        view = item.info.name
        handle.write("\n-- ----------------------------\n-- view %s\n"
                     "-- ----------------------------\n" % quote_ident(view))
        try:
            if self.options.drop_before_create:
                handle.write(self.dialect.drop_view_sql(view) + "\n")
            ddl = self.dialect.create_view_sql(db, view).rstrip().rstrip(";")
            handle.write(ddl + ";\n")
        except Exception as exc:
            self._record_error(result, "视图 %s 导出失败：%s" % (view, exc))
            result.tables.append(TableResult(view, KIND_VIEW, 0, str(exc)))
            return
        result.tables.append(TableResult(view, KIND_VIEW, 0))
        self.log("    [导出] 视图 %s" % view)

    def _record_error(self, result: DatabaseResult, message: str) -> None:
        result.errors.append(message)
        self.log("    [错误] " + message)

    def _cancelled(self) -> bool:
        return self.cancel_event is not None and self.cancel_event.is_set()
